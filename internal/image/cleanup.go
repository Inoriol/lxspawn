package image

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/Inoriol/lxspawn/internal/deploy"
	"github.com/Inoriol/lxspawn/internal/logger"
)

func isRoot() bool {
	return os.Geteuid() == 0
}

func canWriteToRootfs(rootfsPath string) bool {
	testFile := filepath.Join(rootfsPath, ".lxspawn-write-test")
	f, err := os.Create(testFile)
	if err != nil {
		return false
	}
	f.Close()
	os.Remove(testFile)
	return true
}

func sudoOrDirectForRootfs(rootfsPath string, args ...string) *exec.Cmd {
	if isRoot() || canWriteToRootfs(rootfsPath) {
		return exec.Command(args[0], args[1:]...)
	}
	return deploy.Sudo(args...)
}

func CleanupRootfs(rootfs string) error {
	resolvContent := `# Generated by lxspawn
nameserver 8.8.8.8
nameserver 1.1.1.1
nameserver 8.8.4.4
`
	if err := writeRootfsFile(rootfs, "/etc/resolv.conf", resolvContent, 0644); err != nil {
		return fmt.Errorf("failed to write resolv.conf: %w", err)
	}
	logger.Info("Wrote etc/resolv.conf with public DNS servers")

	securetty := `pts/0
pts/1
pts/2
pts/3
pts/4
pts/5
pts/6
pts/7
pts/8
pts/9
`
	if err := writeRootfsFile(rootfs, "/etc/securetty", securetty, 0644); err != nil {
		return fmt.Errorf("failed to write securetty: %w", err)
	}
	logger.Info("Wrote etc/securetty")

	machineID := filepath.Join(rootfs, "etc", "machine-id")
	if deploy.FileExists(machineID) {
		cmd := sudoOrDirectForRootfs(rootfs, "rm", "-f", machineID)
		if output, err := cmd.CombinedOutput(); err != nil {
			logger.Warn(fmt.Sprintf("failed to remove machine-id: %v (%s)", err, string(output)))
		} else {
			logger.Info("Removed etc/machine-id")
		}
	}

	if err := maskContainerServices(rootfs); err != nil {
		logger.Warn(fmt.Sprintf("failed to mask container services: %v", err))
	}

	return nil
}

func writeRootfsFile(rootfs, relPath, content string, perm uint32) error {
	fullPath := filepath.Join(rootfs, relPath)
	parentDir := filepath.Dir(fullPath)

	if !deploy.FileExists(parentDir) {
		cmd := sudoOrDirectForRootfs(rootfs, "mkdir", "-p", parentDir)
		if output, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("failed to create directory %s: %w (%s)", parentDir, err, string(output))
		}
	}

	cmd := sudoOrDirectForRootfs(rootfs, "tee", fullPath)
	cmd.Stdin = strings.NewReader(content)
	cmd.Stdout = nil
	cmd.Stderr = nil
	if output, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("failed to write file %s: %w (%s)", fullPath, err, string(output))
	}

	permStr := fmt.Sprintf("%04o", perm)
	chmodCmd := sudoOrDirectForRootfs(rootfs, "chmod", permStr, fullPath)
	if output, err := chmodCmd.CombinedOutput(); err != nil {
		return fmt.Errorf("failed to chmod %s: %w (%s)", fullPath, err, string(output))
	}

	return nil
}

func maskContainerServices(rootfs string) error {
	services := []string{
		"systemd-udevd.service",
		"systemd-udevd-control.socket",
		"systemd-udevd-kernel.socket",
		"systemd-modules-load.service",
	}

	systemdDir := filepath.Join(rootfs, "etc", "systemd", "system")
	if !deploy.FileExists(systemdDir) {
		cmd := sudoOrDirectForRootfs(rootfs, "mkdir", "-p", systemdDir)
		if output, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("failed to create systemd system dir: %w (%s)", err, string(output))
		}
	}

	for _, svc := range services {
		link := filepath.Join(systemdDir, svc)
		if deploy.FileExists(link) {
			continue
		}
		cmd := sudoOrDirectForRootfs(rootfs, "ln", "-s", "/dev/null", link)
		if output, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("failed to mask %s: %w (%s)", svc, err, string(output))
		}
		logger.Info(fmt.Sprintf("Masked %s", svc))
	}
	return nil
}
