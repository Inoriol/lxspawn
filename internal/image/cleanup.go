package image

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/Inoriol/lxspawn/internal/logger"
)

func CleanupRootfs(rootfs string) error {
	// Ensure etc directory exists
	etcDir := filepath.Join(rootfs, "etc")
	if err := os.MkdirAll(etcDir, 0755); err != nil {
		return fmt.Errorf("failed to create etc directory: %w", err)
	}

	machineID := filepath.Join(etcDir, "machine-id")
	if err := os.Remove(machineID); err != nil && !os.IsNotExist(err) {
		logger.Warn(fmt.Sprintf("failed to remove machine-id: %v", err))
	} else if err == nil {
		logger.Info("Removed etc/machine-id")
	}

	resolvConf := filepath.Join(etcDir, "resolv.conf")
	if err := os.Remove(resolvConf); err != nil && !os.IsNotExist(err) {
		logger.Warn(fmt.Sprintf("failed to remove resolv.conf: %v", err))
	} else if err == nil {
		logger.Info("Removed etc/resolv.conf")
	}

	resolvContent := `# Generated by lxspawn
nameserver 8.8.8.8
nameserver 1.1.1.1
nameserver 8.8.4.4
`
	if err := os.WriteFile(resolvConf, []byte(resolvContent), 0644); err != nil {
		return fmt.Errorf("failed to write resolv.conf: %w", err)
	}
	logger.Info("Wrote etc/resolv.conf with public DNS servers")

	securetty := filepath.Join(etcDir, "securetty")
	content := `pts/0
pts/1
pts/2
pts/3
pts/4
pts/5
pts/6
pts/7
pts/8
pts/9
`
	if err := os.WriteFile(securetty, []byte(content), 0644); err != nil {
		return fmt.Errorf("failed to write securetty: %w", err)
	}
	logger.Info("Wrote etc/securetty")

	return nil
}
